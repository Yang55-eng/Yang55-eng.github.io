# ---------- where to install ----------
$Dest  = Join-Path $env:USERPROFILE ".workbuddy\skills"
$Final = Join-Path $Dest $SkillName
$LocalZip = if ($PSScriptRoot) { Join-Path $PSScriptRoot $ZipName } else { "" }

$TmpDir = Join-Path $env:TEMP ($SkillName + "-" + [System.Guid]::NewGuid().ToString("N").Substring(0, 8))
$OutZip = $TmpDir + ".zip"
New-Item -ItemType Directory -Path $TmpDir -Force | Out-Null

function Get-Zip($target) {
    # 1) online
    if ($BaseUrl -match '^https?://') {
        $url = $BaseUrl.TrimEnd("/") + "/" + $ZipName
        Say "Downloading $url"
        try {
            [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
            (New-Object Net.WebClient).DownloadFile($url, $target)
            if ((Test-Path $target) -and (Get-Item $target).Length -gt 1000) { return $true }
        } catch {
            Say "online zip unavailable -> falling back"
        }
    }
    # 2) local zip beside this script
    if ($LocalZip -and (Test-Path $LocalZip)) {
        Say "Offline mode: using local $ZipName"
        Copy-Item $LocalZip $target -Force
        return $true
    }
    # 3) embedded payload
    if ($Embedded -and $Embedded.Length -gt 1000) {
        Say "Unpacking embedded package"
        [IO.File]::WriteAllBytes($target, [Convert]::FromBase64String(($Embedded -replace '\s', '')))
        return $true
    }
    return $false
}

try {
    if (-not (Get-Zip $OutZip)) {
        Write-Host "ERROR: no source available (online, local and embedded all failed)."
        exit 1
    }

    Say "Extracting..."
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    [IO.Compression.ZipFile]::ExtractToDirectory($OutZip, $TmpDir)

    $Src = Join-Path $TmpDir $SkillName
    if (-not (Test-Path (Join-Path $Src "SKILL.md"))) {
        if (Test-Path (Join-Path $TmpDir "SKILL.md")) {
            $Src = $TmpDir
        } else {
            $found = Get-ChildItem $TmpDir -Recurse -Filter "SKILL.md" | Select-Object -First 1
            if (-not $found) {
                Write-Host "ERROR: no SKILL.md inside the archive - bad package."
                exit 1
            }
            $Src = $found.Directory.FullName
        }
    }

    if (Test-Path $Final) {
        $bak = $Final + ".bak-" + (Get-Date -Format "yyyyMMdd-HHmmss")
        Say "Existing install found -> backing up to $bak"
        Move-Item $Final $bak
    }

    if (-not (Test-Path $Dest)) {
        New-Item -ItemType Directory -Path $Dest -Force | Out-Null
    }
    Copy-Item $Src $Final -Recurse -Force

    if (-not ((Test-Path (Join-Path $Final "SKILL.md")) -and (Test-Path (Join-Path $Final "scripts\build_report.py")))) {
        Write-Host "ERROR: install incomplete at $Final"
        exit 1
    }

    $nScripts = (Get-ChildItem (Join-Path $Final "scripts") -File -ErrorAction SilentlyContinue).Count
    Say "Installed v$Version to: $Final"
    Say "  SKILL.md + $nScripts scripts"
    Say ""
    Say "Next: restart WorkBuddy, then say:"
    Say '  "generate the lab report from my PPT"'

} finally {
    Remove-Item $OutZip -Force -ErrorAction SilentlyContinue
    Remove-Item $TmpDir -Recurse -Force -ErrorAction SilentlyContinue
}
